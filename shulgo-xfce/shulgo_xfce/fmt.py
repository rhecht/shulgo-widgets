"""Turning ShulGo's JSON into the words the widget shows — the Python side.

This is a PORT of integrations/shulgo-core/format.js, not a rewrite. format.js stays canonical: it is
what the GNOME widget, the GTK app and the Mac/Windows tray all read, and the wording in it is the
product. Python cannot import a JavaScript module, and the machine this file exists for — a Pentium III
with 256 MB of RAM, where gjs is four years old and Electron does not exist — cannot run that one.

Two copies of the wording is a real cost, and the way it is paid is tests/test_fmt.py: it reads
tests/expected.json, which is generated by running format.js itself under node, and asserts this file
produces the same strings from the same input. So the two drifting apart fails a test here rather than
turning up on somebody's laptop. If you change the wording, change format.js first, regenerate, and
then make this file agree.

Pure stdlib on purpose: no GTK, no GLib, no third-party packages. Python 3.9 or newer.

A note on arithmetic, which is where a port like this quietly goes wrong. JavaScript's Math.round
rounds a half upwards (towards +infinity), while Python's round() rounds a half to the nearest even
number: round(12.5) is 12 in Python and 13 in JS. And Number.prototype.toFixed rounds the half of the
*exact binary double* away from zero, where Python's format() is again half-to-even: "%.1f" % 0.25 is
"0.2" here and "0.3" there. Distances and coordinates go through both, so both are reimplemented below
rather than approximated. This is not pedantry: a cache key that rounds differently is a cache that is
never read, and that bug looks exactly like a slow network.
"""

import math
import os
import re
import time
from decimal import Decimal, ROUND_HALF_UP

# The API sends codes; these are the words ShulGo itself uses.
TEFILLAH = {
    'shacharis': 'Shacharis',
    'mincha': 'Mincha',
    'maariv': 'Maariv',
    'selichos': 'Selichos',
    'musaf': 'Musaf',
    'neilah': 'Neilah',
}

FOR_WHOM = {'women': 'Women', 'men': 'Men', 'keilim': 'Keilim'}


# ---- the arithmetic JavaScript does, done the same way ---------------------------------------

def js_round(value):
    """Math.round: the half goes up, towards +infinity. Math.round(-12.5) is -12, not -13."""
    return math.floor(value + 0.5)


def js_to_fixed(value, digits):
    """Number.prototype.toFixed, including its rounding.

    Decimal(float) takes the double's exact binary value, which is the number toFixed actually looks
    at — so (1.005).toFixed(2) comes out "1.00" here as it does in JS, because 1.005 is really
    1.00499999999999989341858963598497211933135986328125.
    """
    quantum = Decimal(1).scaleb(-digits)

    return str(Decimal(float(value)).quantize(quantum, rounding=ROUND_HALF_UP))


def _title_case(text):
    """JS: s.charAt(0).toUpperCase() + s.slice(1). Only the first letter, and '' stays ''."""
    s = '' if text is None else str(text)

    return s[:1].upper() + s[1:]


def _num(value):
    """Number(x) for the cases this file needs, with Number.isFinite's answer as None."""
    if value is None or value is True or value is False:
        return None
    try:
        n = float(value)
    except (TypeError, ValueError):
        return None

    return None if (math.isnan(n) or math.isinf(n)) else n


# ---- labels ----------------------------------------------------------------------------------

def tefillah_label(code):
    if not code:
        return 'Minyan'

    return TEFILLAH.get(code, _title_case(code))


def for_whom_label(code):
    return FOR_WHOM.get(code, _title_case(code))


# ---- time ------------------------------------------------------------------------------------

_ISO = re.compile(
    r'^\s*(\d{4})-(\d{2})-(\d{2})'
    r'[Tt ](\d{2}):(\d{2})(?::(\d{2}))?(?:\.(\d+))?'
    r'\s*(Z|z|[+-]\d{2}:?\d{2})?\s*$'
)


def to_unix(iso):
    """Seconds since the epoch for an ISO 8601 time with an offset, or None.

    Written out rather than handed to datetime.fromisoformat because that only learned to read a
    trailing "Z" in Python 3.11, and the oldest machine this has to run on has 3.11 but Fedora Asahi
    may not. A naive time — no offset at all — is read as local, which is what Date.parse does for
    date-times and what the API never sends anyway.
    """
    if not iso:
        return None
    m = _ISO.match(str(iso))
    if not m:
        return None

    year, month, day, hour, minute = (int(m.group(i)) for i in range(1, 6))
    second = int(m.group(6) or 0)
    zone = m.group(8)

    if zone is None:
        try:
            return int(time.mktime((year, month, day, hour, minute, second, 0, 0, -1)))
        except (OverflowError, ValueError):
            return None

    # days-from-epoch by Howard Hinnant's civil_from_days, so no calendar library is needed
    y = year - (1 if month <= 2 else 0)
    era = (y if y >= 0 else y - 399) // 400
    yoe = y - era * 400
    doy = (153 * (month + (-3 if month > 2 else 9)) + 2) // 5 + day - 1
    doe = yoe * 365 + yoe // 4 - yoe // 100 + doy
    days = era * 146097 + doe - 719468

    at = days * 86400 + hour * 3600 + minute * 60 + second
    if zone in ('Z', 'z'):
        return at

    sign = 1 if zone[0] == '+' else -1
    flat = zone[1:].replace(':', '')

    return at - sign * (int(flat[:2]) * 3600 + int(flat[2:]) * 60)


def now_unix():
    return math.floor(time.time())


def minutes_until(iso, now=None):
    """Minutes from now until an ISO time, worked out locally so a countdown can tick between
    requests instead of asking the server again every minute."""
    at = to_unix(iso)
    if at is None:
        return None

    return math.floor((at - (now_unix() if now is None else now)) / 60)


def countdown(minutes):
    """0 -> "now", 6 -> "in 6 min", 95 -> "in 1h 35m", -4 -> "4 min ago"."""
    if minutes is None:
        return ''
    if minutes == 0:
        return 'now'
    if minutes < 0:
        past = abs(minutes)

        return '%d min ago' % past if past < 60 else '%dh ago' % (past // 60)
    if minutes < 60:
        return 'in %d min' % minutes
    h, m = divmod(minutes, 60)

    return 'in %dh %dm' % (h, m) if m else 'in %dh' % h


def countdown_short(minutes):
    """The short form for the panel: "6m", "1h35"."""
    if minutes is None:
        return ''
    if minutes <= 0:
        return 'now'
    if minutes < 60:
        return '%dm' % minutes
    h, m = divmod(minutes, 60)

    return '%dh%02d' % (h, m) if m else '%dh' % h


def today_iso(when=None):
    """A date as Y-M-D in local time; today by default. Takes a unix time, not a Date."""
    t = time.localtime(time.time() if when is None else when)

    return '%04d-%02d-%02d' % (t.tm_year, t.tm_mon, t.tm_mday)


# ---- distance and travel ---------------------------------------------------------------------

def miles(value):
    """0.49 -> "0.5 mi"; 12.4 -> "12 mi"."""
    n = _num(value)
    if n is None:
        return ''

    return '%s mi' % js_to_fixed(n, 1) if n < 10 else '%d mi' % js_round(n)


def travel(item, mode='drive'):
    """"about 5 min drive" / "12 min walk", or nothing when ShulGo couldn't route it.

    travel_min always matches the mode that was asked for. The item's own travel_walk flag means
    something narrower — you asked to drive, but it's near enough to walk — so the words follow the
    mode first, the way shulgo.com's own pages put it.
    """
    low = (item or {}).get('travel_min')
    if low is None:
        return ''

    if mode == 'walk' or (item or {}).get('travel_walk'):
        return '%s min walk' % low

    return 'about %s min drive' % low


def urgency(item):
    """How a minyan stands against the clock, for the colour of its dot:
    'comfortable' — plenty of room      'tight' — you'd have to leave now
    'missed'      — can't be made       'unknown' — ShulGo couldn't route it
    """
    item = item or {}
    can = item.get('can_make_it')
    # `is False` and `is None` on purpose: JSON false and null are different answers here, and `not
    # can` would call them both 'missed'.
    if can is False:
        return 'missed'
    if can is None:
        return 'unknown'
    buffer_min = _num(item.get('buffer_min'))

    return 'tight' if buffer_min is not None and buffer_min <= 5 else 'comfortable'


# ---- the lines under a minyan ----------------------------------------------------------------

def minyan_subtitle(item, mode='drive'):
    """The one line under a minyan's name: shul, distance, how long to get there, nusach."""
    item = item or {}
    bits = []
    if item.get('kind') == 'live':
        bits.append('Forming now' if (item.get('live') or {}).get('notes') else 'Forming nearby')
    elif (item.get('shul') or {}).get('display_name'):
        bits.append(item['shul']['display_name'])

    d = miles(item.get('distance_miles'))
    if d:
        bits.append(d)
    t = travel(item, mode)
    if t:
        bits.append(t)
    if item.get('nusach'):
        bits.append(item['nusach'])

    return ' · '.join(bits)


def minyan_note(item):
    """The second line, when there is one worth showing: a note, a one-off change, a venue."""
    item = item or {}
    bits = []
    if item.get('kind') == 'standing' and (item.get('shul') or {}).get('venue_label'):
        bits.append(item['shul']['venue_label'])
    if item.get('status') and item.get('status') != 'scheduled':
        bits.append(_title_case(item['status']))
    if item.get('notes'):
        bits.append(item['notes'])

    return ' · '.join(bits)


def minyan_destination(item):
    """Where to send a map app for this minyan."""
    item = item or {}
    if item.get('kind') == 'live':
        return (item.get('live') or {}).get('directions')
    loc = (item.get('shul') or {}).get('location')
    if loc:
        return '%s,%s' % (loc.get('lat'), loc.get('lng'))

    return ((item.get('shul') or {}).get('address') or {}).get('formatted')


def maps_uri(destination):
    """A map link that works on every desktop we build for."""
    if not destination:
        return None
    from urllib.parse import quote

    return ('https://www.google.com/maps/dir/?api=1&destination='
            + quote(str(destination), safe="!'()*-._~"))


# ---- zmanim ----------------------------------------------------------------------------------

def zmanim_list(data, now=None):
    """Zmanim come back as an object; this puts them in clock order and says which is still ahead."""
    now = now_unix() if now is None else now
    rows = []
    for name, z in (data or {}).items():
        if not isinstance(z, dict) or not z.get('time'):
            continue
        at = to_unix(z['time'])
        if at is None:
            continue
        row = dict(z)
        row['name'] = name
        row['at'] = at
        rows.append(row)

    # JS Array.prototype.sort is stable, and so is Python's, so equal times keep the order the
    # object gave them — which for a JSON object is insertion order in both languages.
    rows.sort(key=lambda r: r['at'])

    next_index = next((i for i, r in enumerate(rows) if r['at'] > now), -1)
    for i, r in enumerate(rows):
        r['isNext'] = (i == next_index)
        r['past'] = r['at'] <= now

    return rows


# ---- markup and the machine ------------------------------------------------------------------

def escape_markup(text):
    """Pango reads markup, so anything from the API has to be made safe first. The & goes first."""
    s = '' if text is None else str(text)

    return (s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
            .replace('"', '&quot;').replace("'", '&apos;'))


def system_timezone():
    """The machine's own time zone as an IANA name like "America/Toronto", or None.

    GJS asks Intl for this. There is no such call in the standard library, so this reads what the
    system actually goes by: /etc/localtime is a symlink into the zoneinfo tree on every distribution
    this widget targets, and TZ wins when it is set, as it does for everything else.
    """
    from_env = os.environ.get('TZ')
    if from_env and '/' in from_env:
        return from_env
    try:
        link = os.readlink('/etc/localtime')
    except OSError:
        return None
    parts = link.split('zoneinfo/')

    return parts[-1] if len(parts) > 1 else None


def place_from_timezone(zone):
    """"America/Argentina/Buenos_Aires" -> "Buenos Aires". The city is the part worth saying."""
    if not zone:
        return ''

    return str(zone).split('/')[-1].replace('_', ' ')


def _clock(unix):
    """"1:45 PM" — the shape Intl gives on the machines ShulGo is used on.

    This is the one place the port cannot be exact: JS asks Intl for the locale's own clock, and a
    machine set to a 24-hour locale gets "13:45" there and "1:45 PM" here. It is a cosmetic
    difference in a line that says how old the data is, so it is written down rather than chased, and
    test_fmt.py pins the locale when it compares.
    """
    t = time.localtime(unix)
    hour = t.tm_hour % 12 or 12

    return '%d:%02d %s' % (hour, t.tm_min, 'AM' if t.tm_hour < 12 else 'PM')


def taken_at(unix):
    """"from 1:45 PM", or "from yesterday, 1:45 PM" once it's no longer today's."""
    if not unix:
        return ''
    clock = _clock(unix)
    if today_iso(unix) == today_iso():
        return 'from %s' % clock

    # Whole days apart, counted from each one's local midnight, so a DST change doesn't make
    # yesterday into two days ago.
    def midday(stamp):
        t = time.localtime(stamp)

        return time.mktime((t.tm_year, t.tm_mon, t.tm_mday, 12, 0, 0, 0, 0, -1))

    days = js_round((midday(time.time()) - midday(unix)) / 86400.0)
    if days == 1:
        return 'from yesterday, %s' % clock

    t = time.localtime(unix)
    day = '%s %d %s' % (
        ('Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun')[t.tm_wday],
        t.tm_mday,
        ('Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
         'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec')[t.tm_mon - 1],
    )

    return 'from %s, %s' % (day, clock)


def offline_notice(state, has_anything):
    """What to say when ShulGo can't be reached.

    Kept here, word for word with format.js, so the top bar, the window, the Mac panel and this tray
    all say it the same way — and say it kindly: this is a thing you glance at on your way out of the
    door, not a server you are administering.

    Returns a dict with title/body/short/tone, or None when all is well.
    """
    state = state or {}
    if not state.get('why'):
        return None

    offline = state.get('why') == 'offline'
    taken = taken_at(state.get('staleSince'))

    if has_anything:
        title = 'You’re offline' if offline else 'ShulGo isn’t answering'

        return {
            'tone': 'resting',
            'title': title,
            'body': ('This is the list %s. It’ll catch up on its own.' % taken) if taken
                    else 'Showing what was here a moment ago. It’ll catch up on its own.',
            'short': ('%s — showing the list %s' % (title, taken)) if taken else title,
        }

    title = 'You’re offline' if offline else 'ShulGo isn’t answering just now'

    return {
        'tone': 'resting',
        'title': title,
        'body': 'Nothing saved yet to show you. The moment you’re back, this fills itself in.' if offline
                else 'Nothing saved yet to show you. It keeps trying in the background.',
        'short': title,
    }


def updated_ago(unix, now=None):
    """"Updated 2 min ago", for the footer."""
    if not unix:
        return ''
    mins = math.floor(((now_unix() if now is None else now) - unix) / 60)
    if mins <= 0:
        return 'Updated just now'
    if mins == 1:
        return 'Updated a minute ago'
    if mins < 60:
        return 'Updated %d min ago' % mins
    h = mins // 60

    return 'Updated %d hour%s ago' % (h, '' if h == 1 else 's')
