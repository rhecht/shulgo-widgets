# -*- coding: utf-8 -*-
u"""Turning ShulGo's JSON into the words the widget shows — the Python side.

This is a PORT of integrations/shulgo-core/format.js, not a rewrite. format.js stays canonical: it is
what the GNOME widget, the GTK app and the Mac/Windows tray all read, and the wording in it is the
product. Python cannot import a JavaScript module, and the machine this file exists for — a Pentium III
with 256 MB of RAM, where gjs is four years old and Electron does not exist — cannot run that one.

Two copies of the wording is a real cost, and the way it is paid is tests/test_fmt.py: it reads
tests/expected.json, which is generated by running format.js itself under node, and asserts this file
produces the same strings from the same input. So the two drifting apart fails a test here rather than
turning up on somebody's laptop. If you change the wording, change format.js first, regenerate, and
then make this file agree.

Pure stdlib on purpose: no GTK, no GLib, no third-party packages. **Python 2.5**, which is what
Ubuntu 7.10 shipped and what the Jewbuntu Classic remaster runs on.

This is a port of a port: shulgo-xfce's fmt.py says the same things under Python 3. A third copy of
the wording is only bearable because all three are held to tests/expected.json, generated from
format.js itself, so they cannot drift apart quietly.

Five things are true on 2.5 and not on 3. Each one was verified against the real 2.5.1 in the Gutsy
image rather than assumed, and every one of them would have been invisible until it wasn't:

  Decimal(a_float) is a TypeError; it did not learn to take floats until 2.7.
  Decimal.scaleb arrived in 2.6, math.isnan and math.isinf in 2.6.
  math.floor returns a float, so "%s" of it prints "5.0" where JavaScript prints "5".
  5 / 60 is 0, not 0.083, without `from __future__ import division` - every countdown in this file
  would have been wrong, and wrong in the direction that reads as "now".
  str(u'...') outside ASCII raises UnicodeEncodeError, and simplejson hands back unicode for every
  string in the API's answer. One shul with an accent in its name would have taken the widget down
  on the one machine where nobody can read a traceback.

That last is why there is a _text() below and no bare str() in this file. Everything here is unicode
end to end, encoded to UTF-8 once at the GTK boundary and nowhere else. Every literal carries a u
prefix because 2.5 has no unicode_literals; tools/unicodeify.py puts them there.

A note on arithmetic, which is where a port like this quietly goes wrong. JavaScript's Math.round
rounds a half upwards (towards +infinity), while Python's round() rounds a half to the nearest even
number: round(12.5) is 12 in Python and 13 in JS. And Number.prototype.toFixed rounds the half of the
*exact binary double* away from zero, where Python's format() is again half-to-even: "%.1f" % 0.25 is
"0.2" here and "0.3" there. Distances and coordinates go through both, so both are reimplemented below
rather than approximated. This is not pedantry: a cache key that rounds differently is a cache that is
never read, and that bug looks exactly like a slow network.
"""

from __future__ import division

import math
import os
import re
import time
from decimal import Decimal, ROUND_HALF_UP, getcontext

# math.isnan and math.isinf arrive in 2.6. NaN is the only value that is not equal to itself, and
# infinity is recognised by comparison; both work on 2.5 and say what they mean.
_INF = float(u'1e400')


def _is_nan(n):
    return n != n


def _is_inf(n):
    return n == _INF or n == -_INF


def _text(value):
    u"""Everything in this file is unicode. Nothing is ever str().

    simplejson gives back unicode for every string in the API's answer, and on Python 2, str() of a
    unicode string that is not pure ASCII raises UnicodeEncodeError. A single shul with an accent or
    a curly apostrophe in its name would have brought the widget down.
    """
    if value is None:
        return u''
    if isinstance(value, unicode):
        return value
    if isinstance(value, str):
        return value.decode(u'utf-8', u'replace')

    return unicode(value)

# The API sends codes; these are the words ShulGo itself uses.
TEFILLAH = {
    u'shacharis': u'Shacharis',
    u'mincha': u'Mincha',
    u'maariv': u'Maariv',
    u'selichos': u'Selichos',
    u'musaf': u'Musaf',
    u'neilah': u'Neilah',
}

FOR_WHOM = {u'women': u'Women', u'men': u'Men', u'keilim': u'Keilim'}


# ---- the arithmetic JavaScript does, done the same way ---------------------------------------

def js_round(value):
    u"""Math.round: the half goes up, towards +infinity. Math.round(-12.5) is -12, not -13.

    int() around it because math.floor returns a float on Python 2, and "%s" of 5.0 is "5.0" where
    the JavaScript says "5".
    """
    return int(math.floor(value + 0.5))


def js_to_fixed(value, digits):
    u"""Number.prototype.toFixed, including its rounding.

    toFixed rounds the exact binary value of the double, not the short decimal we write it as — so
    (1.005).toFixed(2) is "1.00", because 1.005 is really
    1.00499999999999989341858963598497211933135986328125.

    Reaching that exact value is the whole difficulty on 2.5. Decimal(a_float) is a TypeError until
    2.7, Decimal.from_float arrives in 2.7, and float.as_integer_ratio in 2.6, so all three obvious
    ways are shut. Decimal(repr(value)) is the tempting fourth and it is wrong: it gives
    Decimal("1.005"), which rounds half-up to "1.01" and disagrees with every other ShulGo client.

    So the double is taken apart with frexp into the integer and power of two it actually is, and
    rebuilt exactly. 2**-n is exact in decimal (it is 5**n over 10**n), so with enough precision
    nothing rounds on the way in — only the quantize at the end, which is the rounding we want.
    Checked against node on 2.5.1: 1.005→"1.00", 0.25→"0.3", 2.5→"3", 12.345→"12.35".
    """
    quantum = Decimal(u'1e-%d' % digits)
    value = float(value)

    mantissa, exponent = math.frexp(value)
    # mantissa lands in [0.5, 1), so mantissa * 2**53 is an integer for every finite double.
    integer = int(mantissa * (1 << 53))
    power = exponent - 53

    # A double written out exactly needs about 1080 significant digits. The precision is put back
    # afterwards so nothing else in the process inherits it.
    saved = getcontext().prec
    try:
        getcontext().prec = 1100
        exact = Decimal(integer)
        if power >= 0:
            exact = exact * (Decimal(2) ** power)
        else:
            exact = exact / (Decimal(2) ** -power)
        out = exact.quantize(quantum, rounding=ROUND_HALF_UP)
    finally:
        getcontext().prec = saved

    return _text(out)


def _title_case(text):
    u"""JS: s.charAt(0).toUpperCase() + s.slice(1). Only the first letter, and '' stays ''."""
    s = _text(text)

    return s[:1].upper() + s[1:]


def _num(value):
    u"""Number(x) for the cases this file needs, with Number.isFinite's answer as None."""
    if value is None or value is True or value is False:
        return None
    try:
        n = float(value)
    except (TypeError, ValueError):
        return None

    return None if (_is_nan(n) or _is_inf(n)) else n


